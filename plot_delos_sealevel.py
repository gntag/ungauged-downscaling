"""
plot_delos_sealevel.py
======================
Two-panel sea-level-rise risk figure for Delos island.

  Left panel  : Delos elevation map (0-200 m colour scale, green → brown)
  Right panel : Risk classification under a 0.8 m sea-level-rise scenario
                  -1 = Underwater     (elevation + rise < 0)
                   0 = High Danger    (0–5 m above adjusted sea level)
                   1 = Medium Danger  (5–10 m above adjusted sea level)
                   2 = Not in Danger  (> 10 m above adjusted sea level)

INPUTS
------
  plt_config.TIF_PATH     — Mapzen/AWS elevation raster clipped to Delos
                            (generated by raster/delos_mapzen_s2coast.py)
  plt_config.S2COAST_SHP  — S2Coast-2023 dissolved polyline for the coastline overlay
  plt_config.SEALEVEL_OUTPUT_PATH — output PNG path

DATA FLOW
---------
  raster/delos_mapzen_s2coast.py  →  delos_mapzen_s2coast.tif  →  this script  →  PNG
"""

