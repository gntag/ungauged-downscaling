def load_results_from_csv(var_key, input_dir=None):
    """
    Read ba_<var_key>.csv written by ba_postprocessing.py.

    The CSV has columns: lon | lat | historical | rcp45_2041_2060 | … (7 cols).

    Returns
    -------
    lons    : (n_points,) float array
    lats    : (n_points,) float array
    results : dict mapping period keys to (n_points,) float arrays
              Period keys match _PANEL_SUBTITLES: 'historical' or (scen, yr_s, yr_e)
    """
    if input_dir is None:
        input_dir = cfg.INPUT_DIR
    path = os.path.join(input_dir, f"ba_{var_key}.csv")
    if not os.path.exists(path):
        raise FileNotFoundError(
            f"CSV not found: {path}\n"
            f"Run ba_postprocessing.py --var {var_key} first."
        )

    df = pd.read_csv(path)
    lons = df["lon"].values
    lats = df["lat"].values

    results = {"historical": df["historical"].values}
    for scen in SCENARIOS:
        for yr_s, yr_e in FUTURE_PERIODS:
            col = f"{scen}_{yr_s}_{yr_e}"
            results[(scen, yr_s, yr_e)] = df[col].values

    return lons, lats, results


