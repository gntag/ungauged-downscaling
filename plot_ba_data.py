#  Auto colour levels
# ══════════════════════════════════════════════════════════════════════════════

def auto_levels(results, vcfg, n=15):
    """
    Compute nice contour levels from the 2nd–98th percentile of the actual
    ensemble data pooled across all 7 panels.

    Non-negative statistics (counts, sums) clamp the lower bound to 0.
    Falls back to vcfg['levels'] if the data are too sparse to compute.

    Parameters
    ----------
    results : dict  — {period_key: (n_points,) array}
    vcfg    : dict  — variable configuration from plt_config.VARIABLES
    n       : int   — target number of break values

    Returns
    -------
    levels : np.ndarray of sorted break values
    """
    all_vals = []
    for arr in results.values():
        if arr is not None:
            finite = arr[np.isfinite(arr)]
            if len(finite):
                all_vals.append(finite)

    if not all_vals:
        return np.unique(vcfg["levels"])

    combined = np.concatenate(all_vals)
    if len(combined) < 4:
        return np.unique(vcfg["levels"])

    stat_type = vcfg["stat_type"]
    vmin = float(np.percentile(combined, 2))
    vmax = float(np.percentile(combined, 98))

    # Override lower bound for non-negative statistics
    if "vmin" in vcfg:
        vmin = float(vcfg["vmin"])
    elif stat_type.startswith(("count_gt", "count_lt")) or stat_type in ("annual_sum", "precip_r99p"):
        vmin = 0.0

    if vmax <= vmin:
        return np.unique(vcfg["levels"])

    # MaxNLocator produces "nice" break values aligned to human-readable steps
    locator = MaxNLocator(nbins=n, steps=[1, 2, 2.5, 5, 10])
    lev = np.asarray(locator.tick_values(vmin, vmax))

    # Ensure 0 is included and is the lower bound for count/sum statistics
    if (stat_type.startswith(("count_gt", "count_lt")) or stat_type == "annual_sum") \
            and "vmin" not in vcfg:
        lev = lev[lev >= 0]
        if len(lev) == 0 or lev[0] > 0:
            lev = np.concatenate([[0.0], lev])
    else:
        tol = (vmax - vmin) * 0.02
        lev = lev[(lev >= vmin - tol) & (lev <= vmax + tol)]

    return lev if len(lev) >= 3 else np.unique(vcfg["levels"])


# ══════════════════════════════════════════════════════════════════════════════
#  Shoreline loading (binary shapefile reader — avoids GeoPandas dependency)
# ══════════════════════════════════════════════════════════════════════════════

def _scan_shp_lines(shp_path, lon0, lon1, lat0, lat1):
    """
    Read Polyline / Polygon records from a shapefile and return those that
    intersect the bounding box (lon0, lon1, lat0, lat1).

    Reads the binary .shp format directly (ESRI Shapefile spec § 3.3 Polygon,
    § 3.2 Polyline) to avoid requiring GeoPandas for this one operation.
    Only shape types 3 (Polyline) and 5 (Polygon) are handled.

    Returns a list of (lons, lats) arrays, one element per part of each record.
    """
    segments = []
    with open(shp_path, "rb") as f:
        f.seek(100)    # skip the 100-byte file header
        while True:
            header = f.read(8)
            if len(header) < 8:
                break
            # Record header: record number (big-endian) + content length in 16-bit words
            _, content_len_words = struct.unpack(">II", header)
            content_bytes = content_len_words * 2

            # First four bytes of record content = shape type (little-endian int32)
            shape_raw = f.read(4)
            if len(shape_raw) < 4:
                break
            shape_type = struct.unpack("<i", shape_raw)[0]

            if shape_type not in (3, 5):
                f.seek(content_bytes - 4, 1)
                continue

            # Bounding box of this record (8 bytes × 4 doubles)
            bbox_raw = f.read(32)
            if len(bbox_raw) < 32:
                break
            xmin, ymin, xmax, ymax = struct.unpack("<dddd", bbox_raw)
            remaining = content_bytes - 36

            # Skip records entirely outside the query bounding box
            if xmax < lon0 or xmin > lon1 or ymax < lat0 or ymin > lat1:
                f.seek(remaining, 1)
                continue

            rest = f.read(remaining)
            if len(rest) < 8:
                continue

            n_parts  = struct.unpack("<i", rest[0:4])[0]
            n_points = struct.unpack("<i", rest[4:8])[0]
            if n_parts < 1 or n_points < 2:
                continue

            # Part start indices into the point array
            parts_end = 8 + n_parts * 4
            parts     = list(struct.unpack(f"<{n_parts}i", rest[8:parts_end]))
            pts_start = parts_end
            pts_bytes = rest[pts_start: pts_start + n_points * 16]
            if len(pts_bytes) < n_points * 16:
                continue

            # Each point is two 64-bit doubles: (X/lon, Y/lat)
            points = np.frombuffer(pts_bytes, dtype="<f8").reshape(n_points, 2)
            for p_i in range(n_parts):
                p_start = parts[p_i]
                p_end   = parts[p_i + 1] if p_i + 1 < n_parts else n_points
                if p_end - p_start < 2:
                    continue
                xy = points[p_start:p_end]
                segments.append((xy[:, 0], xy[:, 1]))

    return segments


_COAST_CACHE = None   # module-level cache so the shapefile is parsed only once


def _load_coastlines(extent):
    """
    Return a list of (lon_array, lat_array) line segments covering 'extent'.

    Tries the high-resolution S2Coast-2023 shapefile first, then falls back
    to the Natural Earth 10 m coastline bundled with Cartopy.

    extent : [lon_min, lon_max, lat_min, lat_max]
    """
    global _COAST_CACHE
    if _COAST_CACHE is not None:
        return _COAST_CACHE

    lon0, lon1, lat0, lat1 = extent
    pad = 0.01   # small buffer to capture coast segments that start just outside
    b0, b1, b2, b3 = lon0 - pad, lon1 + pad, lat0 - pad, lat1 + pad

    if os.path.exists(S2COAST_SHP):
        print("  Loading S2Coast shoreline (sequential binary scan - may take ~60 s)...",
              flush=True)
        try:
            segs = _scan_shp_lines(S2COAST_SHP, b0, b1, b2, b3)
            print(f"  S2Coast: found {len(segs)} line segment(s) in extent.", flush=True)
            if segs:
                _COAST_CACHE = segs
                return _COAST_CACHE
            print("  S2Coast returned 0 segments - falling back to Natural Earth.", flush=True)
        except Exception as exc:
            print(f"  S2Coast scan error ({exc}) - falling back to Natural Earth.", flush=True)

    print("  Using Natural Earth 10m coastline.", flush=True)
    shpfile = shpreader.natural_earth(resolution="10m", category="physical", name="coastline")
    segs = []
    for geom in shpreader.Reader(shpfile).geometries():
        parts = list(geom.geoms) if hasattr(geom, "geoms") else [geom]
        for part in parts:
            xy = np.array(part.coords)
            lx, ly = xy[:, 0], xy[:, 1]
            # Skip segments entirely outside the padded bounding box
            if lx.max() < b0 or lx.min() > b1 or ly.max() < b2 or ly.min() > b3:
                continue
            segs.append((lx, ly))

    _COAST_CACHE = segs
    return _COAST_CACHE


# ══════════════════════════════════════════════════════════════════════════════
#  Grid helpers
# ══════════════════════════════════════════════════════════════════════════════

def values_to_grid(lon, lat, values):
    """
    Map unstructured (lon, lat, value) triples onto a regular 2-D grid.

    Delos points are not on a regular lat/lon grid, so we reconstruct the
    implicit regular grid by treating unique rounded coordinates as cell centres.

    Returns (lon_centers, lat_centers, grid) where grid has shape
    (n_lats, n_lons) and NaN where no point exists.
    """
    lon_c = np.unique(np.round(lon, 9))
    lat_c = np.unique(np.round(lat, 9))
    grid  = np.full((len(lat_c), len(lon_c)), np.nan, dtype=float)
    lon_idx = {v: i for i, v in enumerate(lon_c)}
    lat_idx = {v: i for i, v in enumerate(lat_c)}
    for x, y, v in zip(np.round(lon, 9), np.round(lat, 9), values):
        grid[lat_idx[y], lon_idx[x]] = v
    return lon_c, lat_c, grid


def edges_from_centers(centers):
    """
    Compute cell-edge coordinates from cell-centre coordinates.

    Uses midpoint rule for interior edges; extrapolates by half the first / last
    spacing for the boundary edges.  Needed for pcolormesh which expects edges.
    """
    c = np.asarray(centers, dtype=float)
    if len(c) == 1:
        return np.array([c[0] - 0.5, c[0] + 0.5])
    e = np.empty(len(c) + 1, dtype=float)
    e[1:-1] = (c[:-1] + c[1:]) / 2.0
    e[0]    = c[0]  - (c[1]  - c[0])  / 2.0
    e[-1]   = c[-1] + (c[-1] - c[-2]) / 2.0
    return e


