def _resolve_cmap(cmap_obj):
    """Accept either a Colormap instance or a string name."""
    if isinstance(cmap_obj, mcolors.Colormap):
        return cmap_obj
    return plt.get_cmap(cmap_obj)


def _make_ax(fig, gs_slot, extent, show_xtick_labels=False, show_ytick_labels=False):
    """
    Create one map axes with consistent ticks and aspect ratio.

    Tick intervals are set to 0.005° lon × 0.01° lat — appropriate for Delos
    (~5 km × 5 km grid spacing).  Tick labels are suppressed on non-edge panels
    to reduce clutter in the 4-row figure layout.
    """
    ax = fig.add_subplot(gs_slot)
    lon0, lon1, lat0, lat1 = extent
    ax.set_xlim(lon0, lon1)
    ax.set_ylim(lat0, lat1)
    ax.set_facecolor("white")
    ax.set_aspect("equal", adjustable="box")   # preserves correct shape of the island

    ax.xaxis.set_major_locator(mticker.MultipleLocator(0.005))
    ax.yaxis.set_major_locator(mticker.MultipleLocator(0.01))
    ax.xaxis.set_major_formatter(mticker.FormatStrFormatter("%.3f°"))
    ax.yaxis.set_major_formatter(mticker.FormatStrFormatter("%.3f°"))

    ax.tick_params(axis="both", length=3, width=0.5, pad=2)
    ax.tick_params(axis="x", labelsize=cfg.FONT_TICK, labelbottom=show_xtick_labels)
    ax.tick_params(axis="y", labelsize=cfg.FONT_TICK, labelleft=show_ytick_labels)
    ax.grid(color="#d0d0d0", linewidth=0.4, alpha=0.6, zorder=0)

    return ax


def _draw_data(ax, lons, lats, values, cmap, norm):
    """Render data points as a pcolormesh on the given axes."""
    lon_c, lat_c, grid = values_to_grid(lons, lats, values)
    lon_e = edges_from_centers(lon_c)
    lat_e = edges_from_centers(lat_c)

    cmap_copy = cmap.copy()
    cmap_copy.set_bad(color="white")   # NaN cells (outside island outline) → white

    ax.pcolormesh(lon_e, lat_e, np.ma.masked_invalid(grid),
                  cmap=cmap_copy, norm=norm, shading="auto", zorder=2)


def _draw_coast(ax, coast_lines):
    """Overlay the coastline segments on the axes."""
    for lx, ly in coast_lines:
        ax.plot(lx, ly, color="#222222", linewidth=0.8, zorder=4)


def _annotate_panel(ax, letter, subtitle):
    """Add the panel letter badge and subtitle to the given axes."""
    ax.set_title(subtitle, fontsize=cfg.FONT_PANEL_SUBTITLE, pad=3,
                 loc="center", color="#222222", fontweight="bold")
    ax.text(0.04, 0.97, f"({letter})", transform=ax.transAxes,
            fontsize=cfg.FONT_PANEL_LETTER, fontweight="bold",
            va="top", ha="left", color="#111111", zorder=5,
            bbox=dict(boxstyle="square,pad=0.15", facecolor="white",
                      edgecolor="none", alpha=0.80))


def make_figure(results, lons, lats, vcfg, levels, coast_lines):
    """
    Build the 7-panel publication figure for one variable.

    Layout:
        Row 0: [a] Historical  (columns 0-1)
        Row 1: [b] rcp45 2041-2060  [c] rcp85 2041-2060
        Row 2: [d] rcp45 2061-2080  [e] rcp85 2061-2080
        Row 3: [f] rcp45 2081-2100  [g] rcp85 2081-2100

    A single shared colorbar is placed on the right of all panels.

    Parameters
    ----------
    results     : dict {period_key: (n_points,) array}
    lons, lats  : (n_points,) float arrays of Delos point coordinates
    vcfg        : variable config dict from plt_config.VARIABLES
    levels      : 1-D array of contour break values
    coast_lines : list of (lon_arr, lat_arr) segments from _load_coastlines()
    """
    cmap   = _resolve_cmap(vcfg["cmap"])
    extend = vcfg["extend"]
    levels = np.unique(levels)
    # BoundaryNorm maps data values to discrete color bins defined by 'levels'
    norm   = mcolors.BoundaryNorm(levels, ncolors=cmap.N, clip=False)

    pad  = cfg.MAP_PADDING
    lon0 = float(lons.min()) - pad;  lon1 = float(lons.max()) + pad
    lat0 = float(lats.min()) - pad;  lat1 = float(lats.max()) + pad
    extent = [lon0, lon1, lat0, lat1]

    # Figure height adapts to the island's lat/lon aspect ratio so panels are not distorted
    data_aspect = (lat1 - lat0) / (lon1 - lon0)
    panel_w_est = cfg.FIG_W * 0.73 / 2
    panel_h_est = panel_w_est * data_aspect
    fig_h       = max(4.0 * panel_h_est + 2.0, 8.0)

    fig = plt.figure(figsize=(cfg.FIG_W, fig_h), constrained_layout=True)
    fig.set_constrained_layout_pads(w_pad=0.02, h_pad=0.06, hspace=0.02, wspace=0.02)

    fig.suptitle(vcfg["title"] + "\n", fontsize=cfg.FONT_SUPTITLE, fontweight="bold",
                 va="top", color="#111111")

    gs      = gridspec.GridSpec(4, 4, figure=fig)
    letters = iter(_PANEL_LETTERS)
    all_axes = []

    # Row 0: Historical — occupies the left two columns
    ax_hist = _make_ax(fig, gs[0, 0:2], extent,
                       show_xtick_labels=False, show_ytick_labels=True)
    all_axes.append(ax_hist)
    hist_vals = results.get("historical")
    if hist_vals is not None and not np.all(np.isnan(hist_vals)):
        _draw_data(ax_hist, lons, lats, hist_vals, cmap, norm)
    else:
        ax_hist.text(0.5, 0.5, "No data", transform=ax_hist.transAxes,
                     ha="center", va="center", fontsize=cfg.FONT_NODATA, color="#888888")
    _draw_coast(ax_hist, coast_lines)
    _annotate_panel(ax_hist, next(letters), _PANEL_SUBTITLES["historical"])

    # Rows 1-3: Future scenario panels (2 columns × 3 rows = 6 panels)
    n_future_rows = len(FUTURE_PERIODS)
    for row_i, (yr_s, yr_e) in enumerate(FUTURE_PERIODS, start=1):
        is_bottom = (row_i == n_future_rows)
        for col_i, scen in enumerate(SCENARIOS):
            col_start = col_i * 2
            key  = (scen, yr_s, yr_e)
            ax   = _make_ax(fig, gs[row_i, col_start:col_start + 2], extent,
                            show_xtick_labels=is_bottom,
                            show_ytick_labels=(col_i == 0))
            all_axes.append(ax)
            values = results.get(key)
            if values is not None and not np.all(np.isnan(values)):
                _draw_data(ax, lons, lats, values, cmap, norm)
            else:
                ax.text(0.5, 0.5, "No data", transform=ax.transAxes,
                        ha="center", va="center", fontsize=cfg.FONT_NODATA, color="#888888")
            _draw_coast(ax, coast_lines)
            _annotate_panel(ax, next(letters), _PANEL_SUBTITLES[key])

    # Shared axis labels
    fig.supylabel("Latitude",  fontsize=cfg.FONT_AXES_LABEL, fontweight="bold")
    fig.supxlabel("Longitude", fontsize=cfg.FONT_AXES_LABEL, fontweight="bold")

    # Single colorbar to the right of all panels
    sm = plt.cm.ScalarMappable(cmap=cmap, norm=norm)
    sm.set_array([])
    cb = fig.colorbar(sm, ax=all_axes, location="right", extend=extend,
                      shrink=cfg.CBAR_SHRINK, aspect=cfg.CBAR_ASPECT, pad=0.02)
    cb.ax.set_title(vcfg["unit"], fontsize=cfg.FONT_CBAR_LABEL, pad=8, loc="center")
    cb.ax.tick_params(labelsize=cfg.FONT_CBAR_TICK, length=4, width=0.8)

    # Thin the tick labels when there are many break values
    if len(levels) > 20:
        cb.set_ticks(levels[::4])

    return fig


# ══════════════════════════════════════════════════════════════════════════════
#  Main
# ══════════════════════════════════════════════════════════════════════════════

def main():
    parser = argparse.ArgumentParser(description="Generate bias-adjusted CORDEX ensemble plots from CSVs")
    parser.add_argument("--var", nargs="+", default=None,
                        help="Variable keys to plot (default: all defined in plt_config.VARIABLES)")
    parser.add_argument("--input-dir", default=None,
                        help="Directory containing ba_*.csv files (default: cfg.INPUT_DIR)")
    parser.add_argument("--output-dir", default=None,
                        help="Directory for output .png files (default: cfg.OUTPUT_DIR)")
    args = parser.parse_args()

    input_dir  = args.input_dir  if args.input_dir  else cfg.INPUT_DIR
    output_dir = args.output_dir if args.output_dir else cfg.OUTPUT_DIR

    _setup_style()
    os.makedirs(output_dir, exist_ok=True)

    var_keys = args.var if args.var else list(cfg.VARIABLES.keys())

    # Load the coastline once, using the geographic extent of the first variable's data
    first_key = var_keys[0]
    lons, lats, _ = load_results_from_csv(first_key, input_dir)
    extent = [lons.min() - cfg.MAP_PADDING, lons.max() + cfg.MAP_PADDING,
              lats.min() - cfg.MAP_PADDING, lats.max() + cfg.MAP_PADDING]
    coast_lines = _load_coastlines(extent)

    for var_key in var_keys:
        vcfg = cfg.VARIABLES[var_key]
        print(f"-- {var_key}  ({vcfg['stat_type']}) --")

        lons, lats, results = load_results_from_csv(var_key, input_dir)

        # Apply the per-variable scale factor (e.g. ×10 converts annual → decadal)
        scale = vcfg.get("scale", 1.0)
        if scale != 1.0:
            results = {k: v * scale if v is not None else None
                       for k, v in results.items()}

        # Choose break levels: use exactly cfg levels, or auto-compute from data
        if vcfg.get("use_config_levels", False):
            levels = np.unique(vcfg["levels"])
        else:
            levels = auto_levels(results, vcfg)
        print(f"  levels: {levels[0]:.4g} ... {levels[-1]:.4g}  ({len(levels)} breaks)",
              flush=True)

        fig   = make_figure(results, lons, lats, vcfg, levels, coast_lines)
        fname = os.path.join(output_dir, f"ba_{var_key}.png")
        fig.savefig(fname, dpi=cfg.PLOT_DPI)
        plt.close(fig)
        print(f"  -> saved: {fname}\n")

    print("Done.")


